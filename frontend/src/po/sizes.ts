/**
 * ポーの大きさ。**画面ごとに幅を書かない。**
 *
 * 何が起きていたか
 * ----------------
 * 画面ごとに違う部品が、その場で決めた幅を直書きしていた。390px で
 * 実際に測ると、こうなっていた（見えている背丈）。
 *
 *     コース一覧    35px
 *     ホーム        46px
 *     レッスン     104px   ← コース一覧の 3倍
 *     同じレッスン   81px   ← 進むだけで 22% 縮む
 *
 * 最後の1行がいちばん厄介だった。`StepShell` が
 * `compact={!eyebrow}` と書いていて、**小さな前置き（Lesson 1 など）が
 * 有るか無いかという、ポーとは何の関係もない条件**で背丈が変わっていた。
 * 同じレッスンを進んでいるだけでポーが縮むので、「同じ子がいる」より
 * 「画面ごとに別の画像を置いている」ように見える。
 *
 * 枠ではなく、見えている背丈で決める
 * ----------------------------------
 * 絵の台紙（512×512）には透明の余白が入っていて、**枠の大きさと
 * 見えるポーの大きさは一致しない**。neutral の絵は台紙の 72.3% の
 * 高さしか使っていないので、144px の枠に入れても背丈は 104px になる。
 *
 * だからここは「見えてほしい背丈」で決め、枠は割り戻して出す。
 * 絵を差し替えて余白が変わっても、ここの数字の意味は変わらない。
 *
 * 幅を渡す口を残さない
 * --------------------
 * `size` しか受け取らない形にする。`className` で幅を上書きできると、
 * 急いでいる日に1画面だけ直書きが戻り、また揃わなくなる。
 */

import { PO_REFERENCE } from "./assets";

/**
 * 大きさの段。**役割で選ぶ。画面で選ばない。**
 *
 *     sm          一覧の行、狭い案内。文字の隣に寄り添う大きさ
 *     md          横で控えている場面（考え中・ヒント・つまずき）
 *     lg          話しかける場面（入り・質問・反応・ねぎらい）
 *     celebration Day を終えたとき。ここだけ特別
 *
 * どの場面がどの段かは `course/poPresence.ts` が決める。画面が
 * 決めない——「どの画面に居るか」を画面ごとに決め始めると、全部
 * 足したときに何段あるのか誰にも分からなくなる。
 */
export type PoSize = "xs" | "sm" | "md" | "lg" | "celebration";

/** 見えてほしい背丈（px）。 */
const VISIBLE_HEIGHT: Record<PoSize, number> = {
  /*
    いちばん小さい段。**添えるだけの場面**に使う。

    診断の結果がこれ。あそこの主役は図と「次の一歩」で、ポーは
    ひとこと添えるだけ。56px でも、見出しの右で場所を取っていた。
  */
  xs: 44,
  sm: 56,
  md: 96,
  /*
    話しかけている場面は、控えている場面より一回り大きくする（1.25倍）。

    質問・反応・ねぎらいはポーが主役の瞬間で、そこだけ存在感が要る。
    上げすぎない理由もある——`lg` を使う画面（条件を足す・見比べる・
    完了）は、どれも中身が多くて残りの高さがいちばん少ない。
    1画面に収まらなくなれば、大きくした意味ごと消える。
  */
  lg: 120,
  /*
    Day 完了は1画面まるごとを持つようになった（`DayCompletePage`）。
    重ね画面の上端から覗いていた頃の 132px では、画面の主役に見えない。
    ここだけ、他の段と比べる相手が居ない——比べる先は**画面の高さ**で、
    Pixel 5（727px）の 4分の1弱に当たる 160px にした。
  */
  celebration: 160,
};

/**
 * 見えている背丈から、枠の一辺を出す。
 *
 * 枠は正方形（台紙が 512×512 なので）。中の絵は `poTransform()` が
 * neutral の位置と大きさへ合わせるので、**どの表情でも同じ背丈**になる。
 * だから割り戻しに使うのは neutral の高さ1つでよい。
 */
export function poFrame(size: PoSize): number {
  return Math.round(VISIBLE_HEIGHT[size] / (PO_REFERENCE.height / 100));
}

/** 見えている背丈（px）。検査が「揃っているか」を測るのに使う。 */
export function poVisibleHeight(size: PoSize): number {
  return VISIBLE_HEIGHT[size];
}

/**
 * そのまま style へ渡せる形。
 *
 * Tailwind の `w-36` のような刻みでは、割り戻した数（78 / 132 / 156 /
 * 182px）をちょうど表せない。刻みに寄せると背丈がまた 4〜8px ずれるので、
 * ここは実寸で渡す。
 */
export function poFrameStyle(size: PoSize): { width: string } {
  return { width: `${poFrame(size)}px` };
}

/**
 * 枠に含まれる、見えない余白（px）。
 *
 * 台紙（512×512）のうち、絵が実際に写っているのは中央の一部だけ。
 * neutral は上に 25.2%、下に 2.8%、左右に 20.5% ずつの透明な帯を
 * 抱えている。枠をそのまま並べると、**空けたつもりの余白と、目に
 * 見える余白が食い違う**——`md` なら上に 33px、余分に開く。
 *
 * 置く側は、返った数だけ負の margin で詰める。そうすると
 * 「12px 空ける」と書いた通りに、見えている体から 12px になる。
 *
 * どの表情でも `poTransform()` が neutral の箱へ揃えるので、
 * 見える範囲はいつも neutral のもの。左右は厳密には対称でない
 * （中心が 49.8%）が、ずれは 1px 未満なので幅の半分で足りる。
 */
export interface PoInk {
  top: number;
  bottom: number;
  side: number;
}

export function poInk(size: PoSize): PoInk {
  const frame = poFrame(size);
  const top = PO_REFERENCE.cy - PO_REFERENCE.height / 2;
  return {
    top: (frame * top) / 100,
    bottom: (frame * (100 - top - PO_REFERENCE.height)) / 100,
    side: (frame * (100 - PO_REFERENCE.width)) / 200,
  };
}
