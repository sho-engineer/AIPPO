/**
 * Day を終えた画面に出す、1行。
 *
 * 教材データが持っている到達点（`lesson.outcomes`）の1本目に
 * 「ようになりました」を足す。
 *
 *     読む相手を伝えられる
 *   → 読む相手を伝えられるようになりました
 *
 * なぜ足すのか
 * ------------
 * `outcomes` はコースの一覧や完了画面で**箇条書き**として並ぶので、
 * 言い切りの形（「〜られる」）で書いてある。それを祝いの画面へ
 * そのまま持ってくると、「読む相手を伝えられる」という札が1枚
 * 置いてあるだけになり、**その日に何が変わったのか**を言わない。
 *
 * 逆に、祝いの画面のために全部を「〜ようになりました」で書き直すと、
 * 今度は箇条書きのほうが冗長になる。読む場所ごとに言い方が要る。
 *
 * なぜ文字をつなぐのか
 * --------------------
 * 教材データに祝い用の文をもう1本持たせる手もあるが、9本ぶん
 * **同じことを2通りで書く**ことになり、片方だけ直る日が来る。
 * つなぐ形なら、直すのは1か所で済む。
 *
 * 代わりに、つないで日本語になることを検査で押さえる
 * （`tests/dayOutcome.test.ts` が全コース・全教材を通す）。
 * 言い切りの形でない到達点（「〜しました」「〜が大事」）を書くと
 * そこで落ちる。
 */

import type { Lesson } from "./types";

/** 足す言葉。 */
export const BECAME = "ようになりました";

/**
 * つないで日本語になる形か。
 *
 * 言い切り（辞書形）の動詞は「る」で終わる——「伝えられる」
 * 「分かる」「整理できる」。ここが「た」や名詞で終わっていると、
 * つないだ先が日本語にならない。
 */
export function joinable(outcome: string): boolean {
  return outcome.endsWith("る");
}

/**
 * その日の1行。
 *
 * 到達点が無い教材（診断など）では、技の名前へ倒す。それも無ければ
 * 当たり障りのない1行を出す——ここが空になると、祝いの画面から
 * 「何ができるようになったか」だけが抜ける。
 */
export function dayOutcomeLine(lesson: Lesson): string {
  const first = lesson.outcomes[0];
  if (first) return joinable(first) ? `${first}${BECAME}` : first;
  return lesson.learnedSkills?.[0] ?? "1つできるようになりました";
}
