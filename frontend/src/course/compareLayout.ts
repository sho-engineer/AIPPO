/**
 * 見比べを、横に並べるか縦に積むか。
 *
 * 決め手は好みではなく、**1行に何文字入るか**。
 *
 * 390px の画面で2列に割ると、余白（左右20px）と矢印の場所を引いて
 * 1列は約157px になる。本文は13pxなので、1行におよそ12文字。
 * 120字の段落を入れると10行の細い柱になり、読み比べどころではない。
 *
 * そこで、横に並べてよいのは次のどちらかを満たすときだけにする。
 *
 *   1. 画面が広い（640px 以上）… 1列 約300px ＝ 23文字/行。長さを問わず読める
 *   2. 両方の文が短い … 12文字/行でも数行に収まる
 *
 * 1つ目は CSS の `sm:` で足りるので、ここが受け持つのは2つ目だけ。
 * 画面幅を JS で測らないのは、測ると回転や分割表示のたびに描き直しが要り、
 * しかも最初の1枚が必ず縦で出てから横へ跳ねるため。
 */

/**
 * 「短い」の境目。
 *
 * 60字。12文字/行で5行にあたる。見出しと余白を足しても、
 * 隣の列と高さがそろう範囲に収まる。
 *
 * これ以上を許すと、片方だけが長い組み合わせで段違いになる。
 */
export const SHORT_TEXT_LIMIT = 60;

/**
 * 狭い画面でも横に並べてよいか。
 *
 * 改行を含むものは、字数にかかわらず縦に積む。
 * 箇条書きは1行が短くても行数が伸びるので、細い列に入れると
 * 「柱が2本」になる。
 */
export function fitsSideBySide(first: string, improved: string): boolean {
  for (const text of [first, improved]) {
    if (text.length > SHORT_TEXT_LIMIT) return false;
    if (text.includes("\n")) return false;
  }
  return true;
}
