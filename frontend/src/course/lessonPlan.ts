/**
 * 「今日やること」の図と、Before / After の対応表。
 *
 * なぜ教材データ（`catalog.ts`）に置かないか
 * ------------------------------------------
 * ここにあるのは**図の材料**であって、教材の本文ではない。教材の本文は
 * 3層（同梱・seed・配信）に同じものが要り、1文字ずれると学習者に出る
 * 内容が変わるので、`seed_catalog.json` と突き合わせて守っている。
 * 図の材料まで同じ扱いにすると、線1本の描き替えに DB の移行が要る。
 *
 * 絵（`course/teachingImages.ts`）と同じ置き方にしてある。あちらも
 * 「どのレッスンのどの画面に何を出すか」を画面側の表で持っている。
 *
 * ずれたら落ちる
 * --------------
 * 表と教材データが食い違うと、図だけが古いことを**目では気づけない**
 * ——図はそれらしく描けてしまう。`tests/lessonPlan.test.ts` が、
 *
 *   ・元の文が `beforeExample` と同じか
 *   ・できあがりが `afterExample` と同じか
 *   ・足す条件が、学習者が実際に選べる選択肢にあるか
 *   ・言いかえ前の言葉が、元の文の中に本当にあるか
 *
 * を見張る。教材を書き替えたらここも直す、を機械に思い出させる。
 */

/** AIへ足す条件を1つ。学習者が実際に選ぶ選択肢と同じ言葉にする。 */
export interface PlanAddition {
  /** 何を足すのか（「誰向け？」）。 */
  label: string;
  /** 足す言葉。教材の選択肢にある文字列そのもの。 */
  value: string;
}

/** むずかしい言葉と、その言いかえ。 */
export interface TermSwap {
  /** 元の文に出てくる言葉。 */
  from: string;
  /** できあがりでの言い方。 */
  to: string;
}

export interface LessonPlan {
  /**
   * 図の左上に出す、元の文章の呼び名。
   *
   * 本文そのものは `lesson.beforeExample` から取る（2か所に書かない）。
   */
  sourceLabel: string;
  /** できあがりの呼び名。 */
  resultLabel: string;
  /**
   * 図の下でポーが言う一言。
   *
   * 教材データの `poMessage`（「まず、できあがりを見てみましょう」）は
   * **後ろの画面のための言葉**で、図を見た人への返事になっていない。
   * 図を見て次に浮かぶのは「で、自分は何をするの？」なので、
   * 図の中の＋2つを指して答える。
   */
  poLine: string;
  /** AIに足す条件。2つまで——3つ目からは図ではなく本編で出会う。 */
  additions: PlanAddition[];
  /**
   * 何がどう変わったか。
   *
   * **全文を読み比べさせないため**にある。専門用語がどの言い方に
   * なったのかを並べれば、「意味は同じまま、言い方が変わった」ことが
   * 1目で分かる。長い2文を突き合わせて自力で探させると、
   * 分かりやすくなった実感より先に読む負担が来る。
   */
  swaps: TermSwap[];
}

export const LESSON_PLANS: Record<string, LessonPlan> = {
  rewrite_text: {
    sourceLabel: "専門的な文章",
    resultLabel: "分かりやすい説明",
    poLine: "この2つを足してみよう！",
    /*
      選択肢の文字列をそのまま持つ。図では「AI初心者向け」と縮めたく
      なるが、縮めると**図で見た言葉が本編に出てこない**。探して見つから
      ないほうが、2文字ぶんの読みやすさより高くつく。
    */
    additions: [
      { label: "誰向け？", value: "AI初心者向けに" },
      { label: "どんな言い方？", value: "やさしい口調で" },
    ],
    /*
      言いかえ先は、できあがりの文（`afterExample`）から**そのまま
      抜き出す**。似た言い回しに書き替えると、表を頼りに本文を読んだ人が
      その言葉を見つけられない——表だけが正しくて本文が別のことを
      言っている状態が、いちばん混乱する。
    */
    swaps: [
      { from: "自己注意機構", to: "文章の中にある言葉同士の関係" },
      { from: "Attention Weight", to: "どの言葉に注目するべきか" },
      { from: "Multi-Head Attention", to: "複数の視点から同時に文章を見る" },
    ],
  },
};

/** その教材の図の材料。無ければ図を出さない。 */
export function lessonPlan(lessonId: string): LessonPlan | null {
  return LESSON_PLANS[lessonId] ?? null;
}
