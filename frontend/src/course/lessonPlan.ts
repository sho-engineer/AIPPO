/**
 * 「今日やること」の図と、Before / After の対応表。
 *
 * なぜ教材データ（`catalog.ts`）に置かないか
 * ------------------------------------------
 * ここにあるのは**図の材料**であって、教材の本文ではない。教材の本文は
 * 3層（同梱・seed・配信）に同じものが要り、1文字ずれると学習者に出る
 * 内容が変わるので、`seed_catalog.json` と突き合わせて守っている。
 * 図の材料まで同じ扱いにすると、線1本の描き替えに DB の移行が要る。
 *
 * 絵（`course/teachingImages.ts`）と同じ置き方にしてある。あちらも
 * 「どのレッスンのどの画面に何を出すか」を画面側の表で持っている。
 *
 * ずれたら落ちる
 * --------------
 * 表と教材データが食い違うと、図だけが古いことを**目では気づけない**
 * ——図はそれらしく描けてしまう。`tests/lessonPlan.test.ts` が、
 *
 *   ・元の文が `beforeExample` と同じか
 *   ・できあがりが `afterExample` と同じか
 *   ・足す条件が、学習者が実際に選べる選択肢にあるか
 *   ・言いかえ前の言葉が、元の文の中に本当にあるか
 *
 * を見張る。教材を書き替えたらここも直す、を機械に思い出させる。
 */

/** AIへ足す条件を1つ。学習者が実際に選ぶ選択肢と同じ言葉にする。 */
export interface PlanAddition {
  /** 何を足すのか（「誰向け？」）。 */
  label: string;
  /** 足す言葉。教材の選択肢にある文字列そのもの。 */
  value: string;
}

/** むずかしい言葉と、その言いかえ。 */
export interface TermSwap {
  /** 元の文に出てくる言葉。 */
  from: string;
  /** できあがりでの言い方。 */
  to: string;
}

export interface LessonPlan {
  /**
   * 図の左上に出す、元の文章の呼び名。
   *
   * 本文そのものは `lesson.beforeExample` から取る（2か所に書かない）。
   */
  sourceLabel: string;
  /** できあがりの呼び名。 */
  resultLabel: string;
  /**
   * 「今日のねらい」に添える一言。
   *
   * ねらいの本文（`lesson.goal`）は**何ができるようになるか**しか
   * 言っていない。なぜそれが効くのかを1行だけ足す。
   */
  goalNote: string;
  /**
   * 「完成イメージ」の Before / After に添える一言。
   *
   * 2つを並べただけだと「別の文になった」で終わる。**意味は変えて
   * いない**ことは、並べても形からは読み取れないので言葉で言う。
   */
  changeNote: string;
  /**
   * 図の下でポーが言う一言。
   *
   * 教材データの `poMessage`（「まず、できあがりを見てみましょう」）は
   * **後ろの画面のための言葉**で、図を見た人への返事になっていない。
   * 図を見て次に浮かぶのは「で、自分は何をするの？」なので、
   * 図の中の＋2つを指して答える。
   */
  poLine: string;
  /** AIに足す条件。2つまで——3つ目からは図ではなく本編で出会う。 */
  additions: PlanAddition[];
  /**
   * 何がどう変わったか。
   *
   * **全文を読み比べさせないため**にある。専門用語がどの言い方に
   * なったのかを並べれば、「意味は同じまま、言い方が変わった」ことが
   * 1目で分かる。長い2文を突き合わせて自力で探させると、
   * 分かりやすくなった実感より先に読む負担が来る。
   */
  swaps: TermSwap[];
}

export const LESSON_PLANS: Record<string, LessonPlan> = {
  rewrite_text: {
    sourceLabel: "専門的な文章",
    resultLabel: "分かりやすい説明",
    goalNote: "読む相手と伝え方を足すだけで、同じ内容でも伝わりやすさが変わります。",
    changeNote: "意味は変えずに、相手に合わせて伝わりやすくします。",
    poLine: "この2つを足してみよう！",
    /*
      選択肢の文字列をそのまま持つ。図では「AI初心者向け」と縮めたく
      なるが、縮めると**図で見た言葉が本編に出てこない**。探して見つから
      ないほうが、2文字ぶんの読みやすさより高くつく。
    */
    additions: [
      { label: "誰向け？", value: "AI初心者向けに" },
      { label: "どんな言い方？", value: "やさしい口調で" },
    ],
    /*
      言いかえ先は、**日常語だけで書く**。

      前は、できあがりの文からそのまま抜き出す決まりにしていた。
      表と本文がずれない利点はあるが、そのために本文のほうが
      「専門用語を1つずつ訳しただけ」の形に引きずられていた。
      表は本文の引用ではなく、**むずかしい言葉の言いかえ**なので、
      言いかえとして自然なほうを取る。

      ここに元の用語（Query・Key・Softmax など）が残っていないことは
      `tests/lessonPlan.test.ts` が見張る。残っていたら、それは
      言いかえられていないということ。
    */
    swaps: [
      { from: "自己注意機構", to: "言葉同士の関係を見る仕組み" },
      { from: "Attention Weight", to: "どの言葉に注目するか" },
      { from: "Multi-Head Attention", to: "いくつかの見方を同時に使う" },
    ],
  },
};

/** その教材の図の材料。無ければ図を出さない。 */
export function lessonPlan(lessonId: string): LessonPlan | null {
  return LESSON_PLANS[lessonId] ?? null;
}

// ------------------------------------------------- 見せるぶんだけ切り出す

/**
 * 長い例文から、**見せるぶんだけ**を切り出す。
 *
 * なぜ切るか
 * ----------
 * 「完成イメージ」に元の文章を丸ごと置いていた。Day1 の題材は 202字の
 * 専門文で、それを読み下してからでないと After に進めない——**始める前に
 * いちばん難しい文章を読ませる**形になっていた。ここで要るのは
 * 「どういう文が、どういう文になるか」が分かることだけで、
 * 全文は本編（実際に書き直す画面）で読む。
 *
 * 別に短い例文を書いて持たない
 * ----------------------------
 * 手で書いた抜粋を持つと、教材の本文を直したときに**抜粋だけが古くなる**。
 * しかも本文と見比べないと気づけない。だから本文から機械的に切り出す。
 *
 * 切り方は2通りで、それぞれ理由がある。
 */

/** 何も見つからないときの上限。長い1文で埋め尽くさないため。 */
const MAX = 46;

function cut(text: string, at: number): string {
  return `${text.slice(0, at)}…`;
}

/**
 * 最初のひと区切りだけ（`、` まで）。読点が無ければ頭から切る。
 *
 * Before に使う。専門文は**最初のひと区切りでもう読めない**ので、
 * そこまで見せれば「難しい」は伝わる。続きを見せても、伝わる量は
 * 増えずに読む負担だけが増える。
 */
export function openingClause(text: string): string {
  const at = text.indexOf("、");
  if (at > 0 && at <= MAX) return cut(text, at);
  return text.length > MAX ? cut(text, MAX) : text;
}

/**
 * 最初のひと文だけ（`。` まで）。句点が無ければ頭から切る。
 *
 * After に使う。こちらは**ひと文で意味が通る**ことがそのまま
 * 「分かりやすくなった」の証拠なので、途中で切らずに1文を出す。
 */
export function firstSentence(text: string): string {
  const at = text.indexOf("。");
  if (at > 0) return text.slice(0, at + 1);
  return text.length > MAX ? cut(text, MAX) : text;
}
