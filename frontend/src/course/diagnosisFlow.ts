/**
 * 診断を答え終わってからの、5つの画面。
 *
 * なぜ1画面を割ったか
 * ------------------------
 * 前は結果が1画面だった。図・できていること・次の一歩・おすすめが
 * 同時に出て、しかも下のボタンが「ここから始める」。**読む前に
 * 次へ行く道が目に入る**ので、結果は読まれずに押された。
 *
 * 分けたのは、順番そのものが意味を持つから。
 *
 *     読み取り … 答えから出した4つの段を、そのまま出す
 *     現在地 … 5段階のどこにいるか。まだ Lesson の話はしない
 *     特徴   … 回答から見えた3行と、その元になった自分の答え
 *     4つの力 … ひし形と、強み／次に伸ばす力／次に覚えること
 *     おすすめ … 上の3つを受けた1本。ここで初めて Lesson が出る
 *
 * 1画面＝1アクションの形に戻っただけで、増えているのは押す回数4回。
 *
 * 「分析しています」ではなく「読み取りました」
 * --------------------------------------------
 * ここには一度、4つの観点が順に点く 1.8 秒の画面があった。消した
 * 理由は2つ。**採点は端末の中の計算で終わる**ので待つものが無いこと。
 * そしてあの画面は4つの観点を**白い角丸カードに丸い印**で縦に並べ、
 * 順に青くしていた——直前まで答えていた選択肢と見分けが付かず、
 * **自分が押していない項目に勝手にチェックが付く**ように見えていた。
 *
 * いまの読み取りの画面は、そのどちらでもない。
 *
 *   - 出すのは**結果そのもの**（4つの段）。まだ決まっていないことを
 *     決まりつつあるように見せない
 *   - 形は横棒。選択肢の札とは似ても似つかない
 *   - 押せば止まる。**足止めしない**
 *
 * 診断らしさは、待ち時間ではなく**答えと判定のつながり**で出す
 * ——読み取った段、回答から見えた特徴とその根拠、現在地、ひし形、
 * 強み、次に伸ばす力、おすすめの根拠。
 *
 * なぜ教材データのステップにしないか
 * ----------------------------------
 * ステップを増やすと、3層（同梱・seed・配信）すべてに同じものが要り、
 * 採点も進み具合の分母も動く。ここで変わるのは**結果の見せ方**だけで
 * 教材の中身ではないので、`completion` の1ステップの中の状態にする。
 * 進み具合の帯も「5問」のまま動かない——結果の画面は問いではない。
 *
 * 文言をここに置く理由
 * --------------------
 * 見出しと CTA は `LessonRunner` が下の帯に出し、中身は
 * `DiagnosisResult` が出す。**2つのファイルにまたがる**ので、
 * 片方だけ直すと画面の上と下で言うことがずれる。1か所に持つ。
 */

export const DIAGNOSIS_PHASES = [
  "reading",
  "stage",
  "traits",
  "axes",
  "lesson",
] as const;

export type DiagnosisPhase = (typeof DIAGNOSIS_PHASES)[number];

export interface PhaseCopy {
  /** 見出しの上の小さな肩書き。 */
  eyebrow?: string;
  title: string;
  instruction?: string;
  /** 下の帯の主ボタン。おすすめだけは Day 番号で作るので空。 */
  primary: string;
  /** 主ボタンの下の、細い1行。 */
  secondary?: string;
  /** そのときポーが言うこと。 */
  po: string;
}

