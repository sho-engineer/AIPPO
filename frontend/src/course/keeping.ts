/**
 * 「進める」と「残す」を分ける。
 *
 *     進める … 登録なしでもできる。教材は最後まで通るし、
 *              続きからも始まる（ゲストの鍵で7日）
 *     残す   … 登録した人だけ。目印・自分のプロンプト帳・修了証
 *
 * なぜ分けるか
 * ------------
 * ゲストの鍵は7日で切れる（backend の LEARNER_KEY_MAX_AGE）。
 * 取っておいたつもりのものが、来月には本人からも取り出せない。
 * **残ると思って残したものが黙って消える**のがいちばんよくないので、
 * 取っておくところだけ登録の内側に置く。
 *
 * 学ぶこと自体は無料のまま。試すのに登録は要らない、というのは
 * 変えていない。変えたのは「登録しないまま、いつまでも溜められる」ところ。
 *
 * 1か所に閉じる
 * -------------
 * 判定をあちこちに書くと、目印は付けられるのに修了証は出ない、
 * といった食い違いが出る。画面はこの1つだけを見る。
 * サーバー側の同じ線は `apps/accounts/scope.py` の `can_keep()`。
 * 画面はそれを先回りして出し分けるだけで、**決めているのはサーバー**。
 */

import { useAuth } from "../auth/AuthContext";

export interface Keeping {
  /** 取っておけるか。 */
  canKeep: boolean;
  /**
   * まだ分からない（`me` の返事待ち）。
   *
   * 待つあいだに「登録すると使えます」を出すと、ログイン済みの人に
   * 一瞬だけ出て消える。出し分けは、決まってからにする。
   */
  loading: boolean;
}

export function useKeeping(): Keeping {
  const auth = useAuth();
  return { canKeep: auth.user !== null, loading: auth.loading };
}
